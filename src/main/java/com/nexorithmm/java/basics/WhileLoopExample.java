package com.nexorithmm.java.basics;

public class WhileLoopExample {
    public static void main(String[] args) {

        int i = 1;

        while(i <= 5){
            System.out.println(i);
            i++;
        }

        int age = 1;

        while (age <= 18){
            System.out.println("Teenage");
            age++;
        }

        int number = 10;

        while (number >= 1){
            System.out.println(number);
            number -= 2;
        }

    }
}
