package com.nexorithmm.java.basics;

public class DataTypesExample {
    public static void main(String[] args) {

    //Primitive Data Types
        byte age = 20;
        short marks = 450;
        int salary = 50000;
        long population = 8000000000L;
        float pi = 3.14f;
        double price = 99.99;
        char grade = 'A';
        boolean isPlaced = true;

        //Non-Primitive Data Types
        String name = "Arjun Sarkar";

        /*
        Other Non-Primitive Data Types:
        Arrays, Classes, Objects,Interfaces and Enums
        We will learn them in upcoming lessons.
          */

        System.out.println("Age             : "+age);
        System.out.println("Marks          : "+marks);
        System.out.println("Salary         : "+salary);
        System.out.println("Population  : "+population);
        System.out.println("Pi                : "+pi);
        System.out.println("Price           : "+price);
        System.out.println("Grade          : "+grade);
        System.out.println("Is Placed      : "+isPlaced);
        System.out.println("Name           : "+name);

    }
}
